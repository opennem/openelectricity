/**
 * Declarative metric definitions for the tracker's network metrics section —
 * the network analogue of `facility/metrics/metric-definitions.js`. Each
 * metric turns the shared `NetworkMetricsContext` (built by
 * `buildNetworkMetricsContext` from the charts' visible-range rows, so every
 * number tracks pan/zoom) into a `MetricResult` for a `MetricCard`.
 *
 * The renewables/fossil pair follows the homepage methodology: each is its own
 * share of gross demand — renewables from OE's `generation_renewable` series,
 * fossil from a real fueltech sum — so the two needn't sum to 100%.
 */

import { getNumberFormat } from '$lib/utils/formatters';

const fmt0 = getNumberFormat(0);
const fmt1 = getNumberFormat(1);
const fmt2 = getNumberFormat(2);

/** @typedef {import('./network-metrics-calc.js').NetworkMetricsContext} NetworkMetricsContext */
/** @typedef {import('$lib/components/charts/facility/metrics/metric-definitions.js').MetricResult} MetricResult */

const SHARE_OF_DEMAND = 'Share of gross demand';

/** @type {Record<string, { label: string, description: string, compute: (ctx: NetworkMetricsContext) => MetricResult }>} */
export const NETWORK_METRICS = {
	renewables: {
		label: 'Renewables',
		description:
			'Renewable generation (including rooftop solar) as a share of gross demand over the visible range — the homepage methodology. Legend toggles on the chart don’t affect this figure.',
		compute: (c) =>
			c.renewablesPct != null
				? {
						value: fmt1.format(c.renewablesPct),
						unit: '%',
						subtitle: c.renewablesTrimmed ? 'Partial demand coverage in range' : SHARE_OF_DEMAND
					}
				: { value: '--' }
	},
	fossils: {
		label: 'Fossil Fuels',
		description:
			'Coal, gas and distillate generation summed by fuel tech, as a share of gross demand over the visible range. Measured independently of the renewables share, so the pair needn’t sum to 100%.',
		compute: (c) =>
			c.fossilPct != null
				? { value: fmt1.format(c.fossilPct), unit: '%', subtitle: SHARE_OF_DEMAND }
				: { value: '--' }
	},
	demand: {
		label: 'Average Demand',
		description:
			'Mean gross demand (operational demand plus rooftop solar) over the visible range.',
		compute: (c) =>
			c.demandAvgMW != null ? { value: fmt0.format(c.demandAvgMW), unit: 'MW' } : { value: '--' }
	},
	peakDemand: {
		label: 'Peak Demand',
		description:
			'The interval with the highest gross demand in the visible range. Hover to highlight the period on the charts.',
		compute: (c) => {
			const p = c.peakDemand;
			if (!p) return { value: '--' };
			return {
				value: fmt0.format(p.value),
				unit: p.isPower ? 'MW' : 'MWh',
				subtitle: p.periodLabel,
				highlightTime: p.time
			};
		}
	},
	avgPrice: {
		label: 'Average Price',
		description:
			'Time-weighted average spot price over the visible range — a plain average of the price intervals, not volume-weighted.',
		compute: (c) =>
			c.avgPrice != null ? { value: fmt2.format(c.avgPrice), unit: '$/MWh' } : { value: '--' }
	},
	generation: {
		label: 'Total Generation',
		description:
			'Energy generated by all source fuel techs over the visible range. Imports and loads (charging, pumping, exports) are excluded.',
		compute: (c) =>
			c.generationMWh != null
				? { value: fmt0.format(c.generationMWh), unit: 'MWh', subtitle: 'Excludes imports' }
				: { value: '--' }
	}
};

/** Ordered metric keys — the same list for every network/region scope. */
export const NETWORK_METRIC_KEYS = [
	'renewables',
	'fossils',
	'demand',
	'peakDemand',
	'avgPrice',
	'generation'
];
